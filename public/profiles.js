/** Hızlı erişim için kimlikten profile eşleme. */
export const PROFILES = Object.fromEntries(
  PROFILE_GROUPS.flatMap((group) =>
    group.profiles.map((profile) => [profile.id, { ...profile, group }]),
  ),
);

export function filterProfiles(query) {
  const needle = String(query || "").trim().toLocaleLowerCase("tr");
  if (!needle) return PROFILE_GROUPS;
  return PROFILE_GROUPS.map((group) => ({
    ...group,
    profiles: group.profiles.filter((profile) =>
      [profile.label, profile.make, profile.model, profile.tag, group.label]
        .join(" ")
        .toLocaleLowerCase("tr")
        .includes(needle),
    ),
  })).filter((group) => group.profiles.length > 0);
}
